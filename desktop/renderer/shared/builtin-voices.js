export function additionalVoicesAccepted(settings = {}) {
  return settings.avoidRestrictedVoices === false && settings.additionalVoiceTermsAccepted === ADDITIONAL_VOICE_TERMS_REVISION &&
    ['personalNoncommercial', 'licensed'].includes(settings.additionalVoiceUse);
}

export function builtinVoiceAllowed(voice, settings) {
  return !voice.requiresAdditionalConsent || additionalVoicesAccepted(settings);
}
